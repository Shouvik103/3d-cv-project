"""Publish compact two-method evidence from completed sequential experiments."""
from pathlib import Path
import argparse,json,shutil,sys,tempfile
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from experiments.protocol import ROOT,ORDER
from experiments.classical_evidence import derive
from runtime import write_json


def report(root,destination):
    root,destination=Path(root).resolve(),Path(destination).resolve()
    ledger=json.loads((root/'experiment_status.json').read_text())
    if any(ledger['experiments'][key]['status'] not in ('completed','limited') for key in ORDER):
        raise ValueError('Finish/address every stage before publishing the consolidated measured record')
    # Capture only compact records. Legacy aggregate plots are regenerated by
    # derive; existing reconstruction geometry and raw image/model data stay local.
    with tempfile.TemporaryDirectory(prefix='classical-evidence-') as temporary:
        compact=Path(temporary)
        for name in ['experiment_status.json','protocol.yaml']:
            shutil.copy2(root/name,compact/name)
        names={'results.json','performance.json','evaluation.json','gt_evaluation.json','summary.json','status.json','variant.yaml','reuse.json','inputs.json','gt_provenance.json','camera_convention_check.json','source_attempts.json'}
        for stage in ORDER:
            for p in (root/stage).rglob('*'):
                if not p.is_file():continue
                rel=p.relative_to(root)
                if any(part.startswith('vggt') for part in rel.parts):continue
                if p.name not in names and not (any(part in ('ours','colmap') for part in rel.parts) and p.name in ('gt_comparison.png','gt_comparison.pdf','interactive_mesh.html','interactive_mesh.json')):continue
                target=compact/rel;target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,target)
        for p in (root/'datasets').rglob('inputs.json'):
            target=compact/p.relative_to(root);target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,target)
        renders=root if all((root/('M4' if m=='ours' else 'M5')/m/'reconstruction.png').exists() for m in ('ours','colmap')) else None
        count=derive(compact,destination,renders)
    lines=['# Classical experiment results','',f'Retained measurements from `{root.name}`; Our SfM and COLMAP only. Figures are regenerated from those measurements, not new reconstruction runs. Failures and unavailable values remain visible.','', '| Stage | Status | Measured results |','| --- | --- | --- |']
    for stage in ORDER:
        target=destination/stage/'RESULTS.md'
        try:relative='../'+str(target.relative_to(ROOT))
        except ValueError:relative=str(target)
        lines.append(f'| {stage} | {ledger["experiments"][stage]["status"]} | [Table and scope]({relative}) |')
    lines+=['','Camera agreement with COLMAP is not independent GT accuracy. Temple cameras and the fountain mesh have explicitly supplied GT references. M5 couples camera, sparse landmark alignment and ROI effects; fusion-held-out photos participated in camera estimation. Read coverage with masked rendering scores. Source hashes are recorded in the evidence collection.','', 'No final IEEE report, narrated demo or human submission is implied by this record.']
    (ROOT/'docs/EXPERIMENT_RESULTS.md').write_text('\n'.join(lines)+'\n')
    print('Published',count,'classical evidence files')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,default=ROOT/'results/experiments_20261118');p.add_argument('--evidence',type=Path,default=ROOT/'validation/experiments_20261119_classical');a=p.parse_args();report(a.out,a.evidence)
