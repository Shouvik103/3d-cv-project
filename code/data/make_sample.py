"""Generate original, redistributable multiview test images with exact poses.

Textured fronto-parallel tiles at different depths provide real projected
image texture for SIFT; this is a synthetic smoke test, not a real-scene benchmark.
"""
import argparse
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import cv2
import numpy as np
import yaml
from runtime import write_json
from sfm.io_utils import save_ply


def generate(out, seed=7):
    rng = np.random.default_rng(seed)
    folder = out/'images'; folder.mkdir(parents=True, exist_ok=True)
    K = np.array([[700., 0, 400], [0, 700, 300], [0, 0, 1.]])
    tiles = []
    for iy in range(4):
        for ix in range(5):
            c = np.array([(ix-2)*.65, (iy-1.5)*.65, rng.uniform(-.65, .65)])
            corners = c + np.array([[-.27, -.27, 0], [.27, -.27, 0], [.27, .27, 0], [-.27, .27, 0]])
            texture = rng.integers(0, 256, (80, 80), dtype=np.uint8)
            texture = cv2.resize(texture, (160, 160), interpolation=cv2.INTER_NEAREST)
            texture = cv2.cvtColor(texture, cv2.COLOR_GRAY2BGR)
            cv2.putText(texture, str(iy*5+ix), (15, 100), cv2.FONT_HERSHEY_SIMPLEX, 1.5, (10, 10, 255), 3)
            tiles.append((corners, texture))
    poses = dict(image_names=[], registered=[], K={}, R={}, t={}, image_size={}); records = {}
    for i, a in enumerate(np.linspace(-.3, .3, 8)):
        C = np.array([4.3*np.sin(a), .25*np.cos(2*a), -4.3*np.cos(a)])
        z = -C/np.linalg.norm(C); x = np.cross([0., 1., 0.], z); x /= np.linalg.norm(x)
        y = np.cross(z, x); R = np.stack([x, y, z]); t = -R @ C
        image = np.full((600, 800, 3), 25, dtype=np.uint8)
        for corners, texture in sorted(tiles, key=lambda pair: np.mean((R @ pair[0].T + t[:, None])[2]), reverse=True):
            q = (K @ (R @ corners.T+t[:, None])).T
            xy = (q[:, :2]/q[:, 2:]).astype(np.float32)
            H = cv2.getPerspectiveTransform(np.array([[0, 0], [159, 0], [159, 159], [0, 159]], np.float32), xy)
            warped = cv2.warpPerspective(texture, H, (800, 600))
            mask = cv2.warpPerspective(np.full((160, 160), 255, np.uint8), H, (800, 600))
            image[mask > 250] = warped[mask > 250]
        name = f'view_{i:02d}.png'; cv2.imwrite(str(folder/name), image)
        poses['image_names'].append(name); poses['registered'].append(name)
        poses['K'][name], poses['R'][name], poses['t'][name] = K.tolist(), R.tolist(), t.tolist()
        poses['image_size'][name] = [800, 600]
        records[name] = dict(K=K.tolist(), image_size=[800, 600], source='synthetic_exact')
    (out/'intrinsics.yaml').write_text(yaml.safe_dump(dict(images=records)))
    write_json(out/'gt_poses.json', poses)
    write_json(out/'provenance.json', dict(generator='code/data/make_sample.py', seed=seed, description='Original generated textures on 20 tiles at varying depths; synthetic only'))
    save_ply(np.concatenate([c for c, _ in tiles]), None, out/'tile_corners.ply')
    (out/'README.md').write_text('Original synthetic multiview scene generated by `code/data/make_sample.py --out sample_data/scene_small`. Eight 800x600 images, exact calibration and poses. This tests image-based reconstruction; it is not a real-world benchmark. No third-party images or weights.\n')
    print('Generated', out)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__); p.add_argument('--out', type=Path, default=Path('sample_data/scene_small'))
    a = p.parse_args(); generate(a.out)
